class _FakeProvider(LLMProvider):
    """A fake LLM provider that returns a controlled JSON response."""

    def __init__(self, response_text: str) -> None:
        self._response_text = response_text
        self.calls: list[dict[str, Any]] = []

    def count_tokens(
        self,
        *,
        messages: list[dict[str, object]],
        tool_schemas: list[dict[str, object]],
        system: str | None = None,
    ) -> int:
        return 0

    def context_window(self) -> int:
        return 64_000

    async def chat(
        self,
        messages: list[dict[str, object]],
        tool_schemas: list[dict[str, object]],
        bus: EventBus,
        run_id: str,
        *,
        step: int = 0,
        system: str | None = None,
    ) -> LlmResponse:
        self.calls.append(
            {
                "messages": messages,
                "tool_schemas": tool_schemas,
                "run_id": run_id,
                "system": system,
            }
        )
        return LlmResponse(
            stop_reason="end_turn",
            text=self._response_text,
            usage=UsageStats(input_tokens=1, output_tokens=1),
        )


def _make_python_project(root: Path) -> None:
    root.mkdir(parents=True, exist_ok=True)
    (root / "pyproject.toml").write_text(
        '[project]\nname = "demo"\nversion = "0.1.0"\nrequires-python = ">=3.12"\n',
        encoding="utf-8",
    )
    (root / "uv.lock").write_text("# This file is automatically generated\n", encoding="utf-8")
    (root / "README.md").write_text("# Demo\n\nA Python demo.\n", encoding="utf-8")
    src = root / "src" / "demo"
    src.mkdir(parents=True)
    (src / "__init__.py").write_text("__version__ = '0.1.0'\n", encoding="utf-8")
    tests = root / "tests"
    tests.mkdir()
    (tests / "test_demo.py").write_text("def test_demo(): pass\n", encoding="utf-8")


def _make_node_project(root: Path) -> None:
    root.mkdir(parents=True, exist_ok=True)
    (root / "package.json").write_text(
        '{\n  "name": "demo",\n  "version": "1.0.0",\n'
        '  "scripts": {\n    "start": "node src/index.js",\n'
        '    "test": "jest",\n    "build": "tsc"\n  },\n'
        '  "dependencies": {\n    "express": "^4.0.0"\n  }\n}\n',
        encoding="utf-8",
    )
    src = root / "src"
    src.mkdir()
    (src / "index.js").write_text("console.log('hello');\n", encoding="utf-8")
    tests = root / "tests"
    tests.mkdir()
    (tests / "index.test.js").write_text("test('ok', () => {});\n", encoding="utf-8")


def test_scanner_detects_python_project(tmp_path: Path) -> None:
    """Python 项目识别语言、依赖、测试命令和关键目录。"""
    root = tmp_path / "pyproj"
    _make_python_project(root)

    scan = scan_project(root)

    assert scan.language == "python"
    assert "pyproject.toml" in scan.key_files
    assert "uv.lock" in scan.key_files
    assert any("src" in e for e in scan.entries)
    assert any("tests" in e for e in scan.entries)
    assert any("uv sync" in cmd for cmd in scan.commands)
    assert any("pytest" in cmd for cmd in scan.commands)
    assert any("ruff" in cmd for cmd in scan.commands)
    assert any("mypy" in cmd for cmd in scan.commands)


