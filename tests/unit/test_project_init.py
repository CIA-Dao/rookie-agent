def test_cli_cmd_init_uses_project_init_service(monkeypatch: pytest.MonkeyPatch) -> None:
    """CLI `my-agent init` 复用 project-init service。"""
    calls: list[tuple[Path, LLMProvider | None]] = []

    async def _recording_run(self: ProjectInitService) -> InitResult:
        calls.append((self.root, self.provider))
        return InitResult(messages=["ok"], files_created=[], files_updated=[], status="success")

    monkeypatch.setattr(ProjectInitService, "run", _recording_run)

    cmd_init()

    assert len(calls) == 1
    assert calls[0][0] == Path.cwd()


async def test_tui_init_branch_uses_project_init_service(monkeypatch: pytest.MonkeyPatch) -> None:
    """TUI `/init` 复用同一个 ProjectInitService。"""
    from my_agent.tui import app as tui_app

    calls: list[tuple[Path, LLMProvider | None]] = []

    async def _recording_run(self: ProjectInitService) -> InitResult:
        calls.append((self.root, self.provider))
        return InitResult(messages=["ok"], files_created=[], files_updated=[], status="success")

    monkeypatch.setattr(ProjectInitService, "run", _recording_run)

    class _FakeLog:
        lines: list[str] = []

        def write(self, text: str) -> None:
            self.lines.append(text)

    class _FakeStatus:
        activities: list[str] = []

        def set_activity(self, activity: str, detail: str = "") -> None:
            self.activities.append(activity)

        def finish(self, status: str) -> None:
            self.activities.append(f"finish:{status}")

    class _FakePalette:
        display = False

        def close(self) -> None:
            pass

    chat_calls: list[tuple[str, str]] = []

    async def _fake_add_chat(role: str, content: str) -> MagicMock:
        chat_calls.append((role, content))
        return MagicMock()

    app = tui_app.MyAgentTuiApp("127.0.0.1", 7437)
    app._busy = False
    app._client = None  # type: ignore[assignment]
    app._session_id = None  # type: ignore[assignment]

    log = _FakeLog()
    status = _FakeStatus()

    def _fake_query_one(selector: str, widget_type: type[Any] | None = None) -> Any:
        if selector == "#log":
            return log
        if selector == "#run-status":
            return status
        if selector == "#slash-palette":
            return _FakePalette()
        return MagicMock()

    monkeypatch.setattr(app, "query_one", _fake_query_one)
    monkeypatch.setattr(app, "_clear_prompt", lambda: None)
    monkeypatch.setattr(app, "_focus_prompt", lambda: None)
    monkeypatch.setattr(app, "_add_chat", _fake_add_chat)

    await app._submit_prompt_text("/init")

    assert len(calls) == 1
    assert calls[0][0] == Path.cwd()
    assert any("init" in a or "analyz" in a.lower() for a in status.activities)
    assert any("ok" in line for line in log.lines)
    assert ("user", "/init") in chat_calls
