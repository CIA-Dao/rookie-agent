def test_scanner_ignores_cache_and_sensitive_files(tmp_path: Path) -> None:
    """忽略 cache、node_modules、runs 和敏感文件。"""
    root = tmp_path / "proj"
    root.mkdir()
    (root / "README.md").write_text("# Proj\n", encoding="utf-8")
    (root / "package.json").write_text('{"name":"proj"}', encoding="utf-8")

    ignored_dirs = [
        ".git",
        ".venv",
        "venv",
        "__pycache__",
        ".pytest_cache",
        ".mypy_cache",
        ".ruff_cache",
        "node_modules",
        "runs",
        "dist",
        "build",
    ]
    for name in ignored_dirs:
        (root / name).mkdir(exist_ok=True)
        (root / name / "file.txt").write_text("secret", encoding="utf-8")

    sensitive_files = [".env", "secret.pem", "credentials.json", "api.key", "id_rsa"]
    for name in sensitive_files:
        (root / name).write_text("sk-abc123", encoding="utf-8")

    scan = scan_project(root)

    for name in ignored_dirs:
        assert name + "/" not in scan.entries, f"{name} should be ignored"
    for name in sensitive_files:
        assert name not in scan.entries, f"{name} should be ignored"

    # Ignored directories appear in skipped; sensitive files also listed there.
    skipped_names = {note.split(":", 1)[0] for note in scan.skipped}
    for name in ignored_dirs:
        assert name in skipped_names, f"{name} should be listed as skipped"
    for name in sensitive_files:
        assert name in skipped_names, f"{name} should be listed as skipped"

    for name in sensitive_files:
        assert any(name in p for p in scan.sensitive_paths), f"{name} should be sensitive"

    for content in scan.file_contents.values():
        assert "sk-abc123" not in content


def test_scanner_size_limits(tmp_path: Path) -> None:
    """扫描大小边界：超限时仍能完成并给出 skipped。"""
    root = tmp_path / "proj"
    root.mkdir()
    (root / "small.txt").write_text("small", encoding="utf-8")
    (root / "medium.txt").write_text("x" * 100, encoding="utf-8")
    (root / "large.txt").write_text("x" * 1000, encoding="utf-8")

    limits = ScanLimits(max_file_size=50, max_total_bytes=80, max_files=2)
    scan = scan_project(root, limits=limits)

    total = sum(len(c.encode("utf-8")) for c in scan.file_contents.values())
    assert total <= limits.max_total_bytes
    assert len(scan.file_contents) <= limits.max_files
    assert any("large.txt" in note or "size" in note.lower() for note in scan.notes)


